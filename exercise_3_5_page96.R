#Generating a random sample of size 1000
# from the exercise 3.5. p. 96
# textbook Maria L. Rizzo.
x=0
n <- 1000
u <- runif(n)

for(i in 1:n){
  if(u[i]<= 0.1){
    x[i]<-0
  }else if((0.1<u[i])&&(u[i]<=0.3)){
    x[i]<-1
  }else if((0.3<u[i])&&(u[i]<=0.5)){
    x[i]<-2
  }else if((0.5<u[i])&&(u[i]<=0.7)){
    x[i]<-3
  }else{
    x[i]<-4}
}
x
# probability Bernouilli distribution with 
# the probability of success p=0.4
round(table(x)/n,1)


